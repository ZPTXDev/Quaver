/**
 * Script to generate TypeScript types from locale files.
 * This enables autocomplete and type safety for locale string paths.
 */

import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Constants for JSDoc comment formatting
const MAX_COMMENT_LENGTH = 100;
const TRUNCATION_LENGTH = 97;

/**
 * Recursively generate all possible string paths from a nested object with their values
 * @param {Record<string, string | Record<string, any>>} obj - The nested object
 * @param {string} prefix - The current path prefix
 * @returns {Array<{path: string, value: string}>} Array of paths with their values
 */
function generatePathsWithValues(obj, prefix = '') {
    const paths = [];

    for (const key in obj) {
        const value = obj[key];
        const currentPath = prefix ? `${prefix}.${key}` : key;

        if (typeof value === 'string') {
            paths.push({ path: currentPath, value });
        } else if (typeof value === 'object' && value !== null) {
            paths.push(...generatePathsWithValues(value, currentPath));
        }
    }

    return paths;
}

/**
 * Escape special characters in string for JSDoc
 * @param {string} str - The string to escape
 * @returns {string} The escaped string
 */
function escapeForJSDoc(str) {
    return str
        .replace(/\\/g, '\\\\')
        .replace(/\*/g, '\\*')
        .replace(/\n/g, ' ')
        .replace(/\r/g, '');
}

/**
 * Main function to generate locale types
 */
async function generateLocaleTypes() {
    const localesDir = resolve(__dirname, '..', 'locales', 'en');
    const outputPath = resolve(__dirname, '..', 'src', 'lib', 'util', 'LocaleKeys.d.ts');

    const localeFiles = readdirSync(localesDir).filter(file => file.endsWith('.js'));

    const allPathsWithValues = [];

    // Load each locale file and extract paths with values
    for (const file of localeFiles) {
        const categoryName = file.split('.')[0].toUpperCase();
        const filePath = resolve(localesDir, file);

        // Import the file using a properly formatted file URL
        const fileUrl = new URL(`file:///${filePath.replace(/\\/g, '/')}`);
        const module = await import(fileUrl.href);
        const localeData = module.default;

        // Generate paths with values for this category
        const categoryPaths = generatePathsWithValues(localeData);

        // Prefix each path with the category name
        const prefixedPaths = categoryPaths.map(item => ({
            path: `${categoryName}.${item.path}`,
            value: item.value,
        }));
        allPathsWithValues.push(...prefixedPaths);
    }

    // Sort paths for readability
    allPathsWithValues.sort((a, b) => a.path.localeCompare(b.path));

    // Generate the type members with JSDoc comments showing the English string
    const typeMembers = allPathsWithValues.map(({ path, value }) => {
        const escapedValue = escapeForJSDoc(value);
        // Truncate long strings for readability
        const displayValue = escapedValue.length > MAX_COMMENT_LENGTH
            ? escapedValue.substring(0, TRUNCATION_LENGTH) + '...'
            : escapedValue;
        return `    /** ${displayValue} */\n    | '${path}'`;
    }).join('\n');

    // Generate the TypeScript type definition file
    const typeDefinition = `/**
 * Auto-generated type definitions for locale string paths.
 * DO NOT EDIT THIS FILE MANUALLY - it is generated by scripts/generate-locale-types.js
 *
 * To regenerate, run: npm run generate:locale-types
 */

/**
 * Union type of all available locale string paths.
 * Provides autocomplete and type safety when accessing locale strings.
 * Each locale key includes a JSDoc comment showing the English string value.
 *
 * @example
 * guild.locale('DISCORD.INSUFFICIENT_PERMISSIONS.BOT.STAGE')
 * guild.locale('CMD.PLAY.DESCRIPTION')
 */
export type LocaleKey =
${typeMembers};
`;

    // Write the type definition file
    writeFileSync(outputPath, typeDefinition, 'utf-8');

    console.log(`✓ Generated locale types with ${allPathsWithValues.length} paths`);
    console.log(`  Output: ${outputPath}`);
}

// Run the script
generateLocaleTypes().catch(error => {
    console.error('Error generating locale types:', error);
    process.exit(1);
});
